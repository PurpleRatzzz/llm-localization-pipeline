"""How much chrF do wordings that the references do not share cost?

A counterfactual on the golden set: delete a word from every translation whose
reference does not contain it at all, then score again with the same chrF as
scripts/evaluate.py. The gain approximates what the word costs on this metric.
It is an upper bound for a style rule, because the model also uses some of
these words without any rule (config A has no style rules).

- 请: style rule R13 (instructions start with 请).
- 您的: not a style rule. The model adds it on its own, also in config A.
- 账户 / 帐户: style rule R11 (login accounts are 账户). Counted to show
  whether the word occurs in the golden set at all.

Run from the repo root:
    .venv/bin/python -I scripts/style_cost.py [RUN_DIR ...]   (default: runs/B runs/E)
Writes reports/style_cost.md.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
# `python -I` does not put scripts/ on sys.path; evaluate.py adds the repo root.
sys.path.insert(0, str(REPO / "scripts"))
import evaluate  # noqa: E402

OUT = REPO / "reports" / "style_cost.md"
WORDS = ["请", "您的"]
COUNTED = ["请", "您的", "账户", "帐户"]


def without(hyps: list[str], refs: list[str], word: str) -> list[str]:
    """Delete `word` from each translation whose reference has no `word`."""
    return [h.replace(word, "") if word not in r else h for h, r in zip(hyps, refs)]


def targets(run_dir: Path, ids: list[str]) -> list[str]:
    with open(run_dir / "segments.jsonl", encoding="utf-8") as f:
        by_id = {row["id"]: row["target"] for row in map(json.loads, f)}
    return [evaluate.plain_text(by_id[i]) for i in ids]


def main(argv: list[str] | None = None) -> None:
    run_dirs = [Path(a) for a in (argv if argv is not None else sys.argv[1:])] or \
        [REPO / "runs/B", REPO / "runs/E"]
    golden = evaluate.load_golden()
    ids = list(golden)
    refs = [evaluate.plain_text(golden[i]["reference"]) for i in ids]

    out = ["# chrF cost of wordings the references do not share", "",
           "Generated by `scripts/style_cost.py` on the 200 golden segments. A word is "
           "deleted from every translation whose reference does not contain it, and chrF "
           "is computed again (same normalization as `scripts/evaluate.py`). The gain is "
           "an upper bound on what a style rule costs on this metric.", "",
           "| Run | chrF as run | without 请 | without 您的 | without both |",
           "|---|---:|---:|---:|---:|"]
    for run_dir in run_dirs:
        hyps = targets(run_dir, ids)
        base = evaluate.corpus_chrf(hyps, refs)
        cells = []
        for variant in (without(hyps, refs, "请"), without(hyps, refs, "您的"),
                        without(without(hyps, refs, "请"), refs, "您的")):
            score = evaluate.corpus_chrf(variant, refs)
            cells.append(f"{score:.2f} ({score - base:+.2f})")
        out.append(f"| {run_dir.name} | {base:.2f} | " + " | ".join(cells) + " |")

    count_runs = [REPO / "runs/A"] + [d for d in run_dirs if d.name != "A"]
    out += ["", "Occurrences in the 200 golden segments (config A has no style rules):", "",
            "| Text | " + " | ".join(COUNTED) + " |", "|---|" + "---:|" * len(COUNTED)]
    out.append("| reference | " + " | ".join(str(sum(r.count(w) for r in refs))
                                           for w in COUNTED) + " |")
    for run_dir in count_runs:
        hyps = targets(run_dir, ids)
        out.append(f"| {run_dir.name} | " + " | ".join(str(sum(h.count(w) for h in hyps))
                                                      for w in COUNTED) + " |")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
